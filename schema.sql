CREATE INDEX idx_faceenroll_passenger ON face_enrollment(passenger_id);

CREATE TABLE face_verification_log (
  verification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  passenger_id INTEGER NOT NULL REFERENCES passenger(passenger_id) ON DELETE CASCADE,
  enrollment_id INTEGER REFERENCES face_enrollment(enrollment_id) ON DELETE SET NULL,
  equipment_id INTEGER REFERENCES equipment(equipment_id) ON DELETE SET NULL,
  checkpoint_type VARCHAR(30) CHECK (checkpoint_type IN ('bag_drop','security_gate','boarding_gate','lounge')),
  cosine_similarity NUMERIC(6,4) CHECK (cosine_similarity BETWEEN 0 AND 1),
  match_threshold NUMERIC(6,4) CHECK (match_threshold BETWEEN 0 AND 1),
