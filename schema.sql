  enrollment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  passenger_id INTEGER NOT NULL REFERENCES passenger(passenger_id) ON DELETE CASCADE,
  document_id INTEGER REFERENCES travel_document(document_id) ON DELETE SET NULL,
  equipment_id INTEGER REFERENCES equipment(equipment_id) ON DELETE SET NULL,
  face_embedding_ref VARCHAR(255),
  embedding_model VARCHAR(30),
  enrollment_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  status VARCHAR(20) CHECK (status IN ('active','superseded','revoked'))
