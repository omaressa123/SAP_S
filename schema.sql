CREATE TABLE boarding_log (
  boarding_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  passenger_id INTEGER NOT NULL REFERENCES passenger(passenger_id) ON DELETE CASCADE,
  flight_id INTEGER NOT NULL REFERENCES flight(flight_id) ON DELETE RESTRICT,
  boarding_gate_id INTEGER REFERENCES boarding_gate(boarding_gate_id) ON DELETE SET NULL,
  verification_id INTEGER UNIQUE REFERENCES face_verification_log(verification_id) ON DELETE SET NULL,
