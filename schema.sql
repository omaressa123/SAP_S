  timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_faceverify_passenger_time ON face_verification_log(passenger_id, timestamp DESC);
CREATE INDEX idx_faceverify_timestamp ON face_verification_log(timestamp DESC);

CREATE TABLE passenger_device (
  device_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  passenger_id INTEGER NOT NULL REFERENCES passenger(passenger_id) ON DELETE CASCADE,
  device_type VARCHAR(10) CHECK (device_type IN ('ios','android')),
  push_token VARCHAR(255),
  app_version VARCHAR(20),
  last_active TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_paxdevice_passenger ON passenger_device(passenger_id);

-- 5b. GATES (must exist before Flight.boarding_gate_id)
CREATE TABLE security_gate (
  gate_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location VARCHAR(50),
  zone_id INTEGER REFERENCES zone(zone_id) ON DELETE SET NULL,
  equipment_id INTEGER UNIQUE REFERENCES equipment(equipment_id) ON DELETE SET NULL,
  status VARCHAR(20) CHECK (status IN ('active','inactive','maintenance'))
);

CREATE TABLE boarding_gate (
  boarding_gate_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gate_number VARCHAR(10) NOT NULL,
  zone_id INTEGER REFERENCES zone(zone_id) ON DELETE SET NULL,
  equipment_id INTEGER UNIQUE REFERENCES equipment(equipment_id) ON DELETE SET NULL,
