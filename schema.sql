-- 6b. WAYFINDING GRAPH
CREATE TABLE map_node (
  node_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_id INTEGER REFERENCES zone(zone_id) ON DELETE SET NULL,
  node_type VARCHAR(20) CHECK (node_type IN ('gate','security_gate','kiosk','amenity','junction')),
  label VARCHAR(50),
  x_coord NUMERIC(8,2),
  y_coord NUMERIC(8,2),
  linked_entity_type VARCHAR(20),
  linked_entity_id INTEGER
);

CREATE TABLE map_edge (
  edge_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_node_id INTEGER NOT NULL REFERENCES map_node(node_id) ON DELETE CASCADE,
  to_node_id INTEGER NOT NULL REFERENCES map_node(node_id) ON DELETE CASCADE,
  distance_m NUMERIC(6,2) CHECK (distance_m >= 0),
  walk_time_sec INTEGER CHECK (walk_time_sec >= 0),
  is_accessible BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT chk_edge_no_selfloop CHECK (from_node_id <> to_node_id)
);
CREATE INDEX idx_edge_from ON map_edge(from_node_id);
CREATE INDEX idx_edge_to ON map_edge(to_node_id);

-- 8. ADMIN, CAMERAS & TWIN
CREATE TABLE user_account (
  user_account_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) UNIQUE NOT NULL,
  email VARCHAR(100) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  linked_person_type VARCHAR(20) CHECK (linked_person_type IN ('passenger','staff')),
  linked_person_id INTEGER,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  last_login TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  -- polymorphic FK to passenger/staff enforced in application layer
);

CREATE TABLE camera (
  camera_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location VARCHAR(50),
  zone_id INTEGER REFERENCES zone(zone_id) ON DELETE SET NULL,
  camera_type VARCHAR(30) CHECK (camera_type IN ('identity','security','monitoring')),
  equipment_id INTEGER UNIQUE REFERENCES equipment(equipment_id) ON DELETE SET NULL,
  status VARCHAR(20) CHECK (status IN ('online','offline'))
);

CREATE TABLE emergency_event (
  event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type VARCHAR(30) CHECK (event_type IN ('fall','smoke_fire','suspicious_bag','crowding','security_breach')),
  zone_id INTEGER REFERENCES zone(zone_id) ON DELETE SET NULL,
  notified_staff_id INTEGER REFERENCES staff(staff_id) ON DELETE SET NULL,
  status VARCHAR(20) CHECK (status IN ('detected','dispatched','resolved')),
  detected_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  resolved_time TIMESTAMPTZ
);
CREATE INDEX idx_emergency_detected ON emergency_event(detected_time DESC);

CREATE TABLE monitoring_alert (
  alert_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camera_id INTEGER REFERENCES camera(camera_id) ON DELETE SET NULL,
  zone_id INTEGER REFERENCES zone(zone_id) ON DELETE SET NULL,
  behavior_type VARCHAR(30) CHECK (behavior_type IN (
    'running','fall','overcrowding','unattended_bag','restricted_area','loitering')),
  severity VARCHAR(20) CHECK (severity IN ('low','medium','high','critical')),
  status VARCHAR(20) CHECK (status IN ('open','resolved')),
  linked_emergency_event_id INTEGER REFERENCES emergency_event(event_id) ON DELETE SET NULL,
  resolved_by_staff_id INTEGER REFERENCES staff(staff_id) ON DELETE SET NULL,
  timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_alert_timestamp ON monitoring_alert(timestamp DESC);

CREATE TABLE digital_twin_position (
  position_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type VARCHAR(20) NOT NULL CHECK (entity_type IN ('passenger','bag')),
  entity_id INTEGER NOT NULL,
  x_coord NUMERIC(8,2),
  y_coord NUMERIC(8,2),
  z_coord NUMERIC(8,2),
  timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW()
  -- polymorphic FK to passenger/bag enforced in digital-twin service
);
CREATE INDEX idx_twin_entity_time ON digital_twin_position(entity_type, entity_id, timestamp DESC);

CREATE TABLE audit_log (
  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_account_id INTEGER REFERENCES user_account(user_account_id) ON DELETE SET NULL,
  action VARCHAR(20) CHECK (action IN ('view','create','update','delete','export')),
  entity_type VARCHAR(30),
  entity_id INTEGER,
  ip_address VARCHAR(45),
  timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW()
