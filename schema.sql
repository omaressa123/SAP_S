
-- Enable pgcrypto for gen_random_uuid() if needed in future (harmless)
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- Auto-update helper for updated_at columns
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 0. REFERENCE: Country (static lookup)
CREATE TABLE country (
  country_code CHAR(2) PRIMARY KEY,
  country_name VARCHAR(60) NOT NULL
);

-- 7. STAFF & PERMISSIONS (created early: many tables FK to staff)
CREATE TABLE department (
  department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_name VARCHAR(60) NOT NULL UNIQUE,
  description VARCHAR(150)
);

CREATE TABLE staff (
  staff_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  department_id INTEGER NOT NULL REFERENCES department(department_id)
    ON DELETE RESTRICT,
  job_title VARCHAR(60),
  employment_type VARCHAR(20) CHECK (employment_type IN ('full_time','part_time','contractor')),
  shift VARCHAR(20) CHECK (shift IN ('morning','evening','night','rotating')),
  contact VARCHAR(30),
  hire_date DATE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_staff_department ON staff(department_id);

CREATE TABLE role (
  role_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name VARCHAR(60) NOT NULL UNIQUE,
  description VARCHAR(150)
);

CREATE TABLE permission (
  permission_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  permission_code VARCHAR(50) NOT NULL UNIQUE,
  category VARCHAR(30) CHECK (category IN ('passenger_data','security','baggage','facilities','staff_admin','energy')),
  description VARCHAR(150)
);

-- Junction: many-to-many Role <-> Permission, composite PK
CREATE TABLE role_permission (
  role_id INTEGER NOT NULL REFERENCES role(role_id) ON DELETE CASCADE,
  permission_id INTEGER NOT NULL REFERENCES permission(permission_id) ON DELETE CASCADE,
  PRIMARY KEY (role_id, permission_id)
);

-- Junction: many-to-many Staff <-> Role, composite PK
CREATE TABLE staff_role (
  staff_id INTEGER NOT NULL REFERENCES staff(staff_id) ON DELETE CASCADE,
  role_id INTEGER NOT NULL REFERENCES role(role_id) ON DELETE CASCADE,
  assigned_date DATE,
  PRIMARY KEY (staff_id, role_id)
);

CREATE TABLE k9_unit (
  k9_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dog_name VARCHAR(50) NOT NULL,
  breed VARCHAR(50),
  specialty VARCHAR(30) CHECK (specialty IN ('explosives','narcotics','general_patrol')),
  handler_staff_id INTEGER REFERENCES staff(staff_id) ON DELETE SET NULL,
  status VARCHAR(20) CHECK (status IN ('active','resting','off_duty','retired')),
  certification_expiry DATE
);
CREATE INDEX idx_k9_handler ON k9_unit(handler_staff_id);

-- 6. WAYFINDING (Zone first: gates/cameras/equipment FK to it)
CREATE TABLE zone (
  zone_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_name VARCHAR(50) NOT NULL,
  terminal VARCHAR(20),
  floor_level INTEGER,
  capacity INTEGER CHECK (capacity >= 0),
  current_occupancy INTEGER NOT NULL DEFAULT 0 CHECK (current_occupancy >= 0)
);

