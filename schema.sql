-- 4. BAGGAGE SECURITY SCREENING
CREATE TABLE baggage_inspection (
  inspection_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bag_id INTEGER NOT NULL REFERENCES bag(bag_id) ON DELETE CASCADE,
  equipment_id INTEGER REFERENCES equipment(equipment_id) ON DELETE SET NULL,
