);

-- 2. FLIGHTS & BOOKINGS
CREATE TABLE airline (
  airline_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  iata_code CHAR(2) UNIQUE
);

CREATE TABLE airport (
  airport_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  iata_code CHAR(3) UNIQUE NOT NULL,
  city VARCHAR(60),
  country_code CHAR(2) REFERENCES country(country_code) ON DELETE RESTRICT
);

CREATE TABLE flight (
  flight_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_number VARCHAR(10) NOT NULL,
  airline_id INTEGER REFERENCES airline(airline_id) ON DELETE RESTRICT,
  origin_airport_id INTEGER REFERENCES airport(airport_id) ON DELETE RESTRICT,
  destination_airport_id INTEGER REFERENCES airport(airport_id) ON DELETE RESTRICT,
  scheduled_departure TIMESTAMPTZ,
  actual_departure TIMESTAMPTZ,
  boarding_gate_id INTEGER REFERENCES boarding_gate(boarding_gate_id) ON DELETE SET NULL,
  status VARCHAR(20) CHECK (status IN ('scheduled','boarding','departed','delayed','cancelled'))
);
CREATE INDEX idx_flight_number ON flight(flight_number);
CREATE INDEX idx_flight_sched_dep ON flight(scheduled_departure);

CREATE TABLE booking (
  booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  passenger_id INTEGER NOT NULL REFERENCES passenger(passenger_id) ON DELETE CASCADE,
  flight_id INTEGER NOT NULL REFERENCES flight(flight_id) ON DELETE RESTRICT,
  booking_reference VARCHAR(10) UNIQUE NOT NULL,
  seat_number VARCHAR(5),
  booking_class VARCHAR(20) CHECK (booking_class IN ('economy','business','first')),
  booking_status VARCHAR(20) CHECK (booking_status IN ('confirmed','checked_in','boarded','cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_booking_passenger ON booking(passenger_id);
CREATE INDEX idx_booking_flight ON booking(flight_id);

CREATE TABLE notification (
  notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  passenger_id INTEGER REFERENCES passenger(passenger_id) ON DELETE CASCADE,
  staff_id INTEGER REFERENCES staff(staff_id) ON DELETE CASCADE,
  channel VARCHAR(20) CHECK (channel IN ('push','sms','email')),
  notification_type VARCHAR(30) CHECK (notification_type IN (
    'gate_change','bag_status','boarding_call','security_notice','staff_task','energy_alert')),
  content VARCHAR(255),
  related_entity_type VARCHAR(30),
  related_entity_id INTEGER,
  sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  read_at TIMESTAMPTZ,
  CONSTRAINT chk_notification_recipient CHECK (passenger_id IS NOT NULL OR staff_id IS NOT NULL)
);
CREATE INDEX idx_notification_sent ON notification(sent_at DESC);
CREATE INDEX idx_notification_passenger ON notification(passenger_id);

-- 3. CHECK-IN & BAGGAGE TAGGING
CREATE TABLE checkin_record (
  checkin_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL UNIQUE REFERENCES booking(booking_id) ON DELETE CASCADE,
  passenger_id INTEGER NOT NULL REFERENCES passenger(passenger_id) ON DELETE CASCADE,
  equipment_id INTEGER REFERENCES equipment(equipment_id) ON DELETE SET NULL,
  checkin_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
DROP TRIGGER IF EXISTS trg_checkin_updated ON checkin_record;
CREATE TRIGGER trg_checkin_updated BEFORE UPDATE ON checkin_record
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE bag (
  bag_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER REFERENCES booking(booking_id) ON DELETE SET NULL,
  passenger_id INTEGER NOT NULL REFERENCES passenger(passenger_id) ON DELETE CASCADE,
  checkin_id INTEGER REFERENCES checkin_record(checkin_id) ON DELETE SET NULL,
  rfid_tag VARCHAR(30) UNIQUE,
  qr_code VARCHAR(100) UNIQUE,
  weight_kg NUMERIC(5,2) CHECK (weight_kg >= 0),
  length_cm NUMERIC(5,2) CHECK (length_cm >= 0),
  width_cm NUMERIC(5,2) CHECK (width_cm >= 0),
  height_cm NUMERIC(5,2) CHECK (height_cm >= 0),
  excess_charge NUMERIC(8,2) DEFAULT 0 CHECK (excess_charge >= 0),
  current_status VARCHAR(20) CHECK (current_status IN ('moving','stationary','loaded','lost')),
  current_location VARCHAR(50),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_bag_passenger ON bag(passenger_id);
CREATE INDEX idx_bag_booking ON bag(booking_id);
CREATE INDEX idx_bag_rfid ON bag(rfid_tag);
DROP TRIGGER IF EXISTS trg_bag_updated ON bag;
CREATE TRIGGER trg_bag_updated BEFORE UPDATE ON bag
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE bag_checkpoint_log (
  checkpoint_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bag_id INTEGER NOT NULL REFERENCES bag(bag_id) ON DELETE CASCADE,
  checkpoint_type VARCHAR(30) CHECK (checkpoint_type IN ('checkin','security_scan','conveyor','loaded_on_aircraft')),
