CREATE INDEX idx_audit_timestamp ON audit_log(timestamp DESC);
CREATE INDEX idx_audit_entity ON audit_log(entity_type, entity_id);

-- 10. SUSTAINABILITY & POWER
CREATE TABLE power_source (
  source_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_type VARCHAR(20) CHECK (source_type IN ('solar','grid','battery_storage')),
  zone_id INTEGER REFERENCES zone(zone_id) ON DELETE SET NULL,
  description VARCHAR(100)
);

CREATE TABLE solar_installation (
  installation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_id INTEGER REFERENCES zone(zone_id) ON DELETE SET NULL,
  equipment_id INTEGER UNIQUE REFERENCES equipment(equipment_id) ON DELETE SET NULL,
  capacity_kw NUMERIC(8,2) CHECK (capacity_kw >= 0),
  panel_count INTEGER CHECK (panel_count >= 0),
  installed_date DATE,
  status VARCHAR(20) CHECK (status IN ('operational','degraded','offline'))
);

CREATE TABLE energy_generation_log (
  log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  installation_id INTEGER NOT NULL REFERENCES solar_installation(installation_id) ON DELETE CASCADE,
  timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  kwh_generated NUMERIC(8,3) NOT NULL CHECK (kwh_generated >= 0)
);
CREATE INDEX idx_gen_install_time ON energy_generation_log(installation_id, timestamp DESC);

CREATE TABLE energy_storage (
  battery_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  installation_id INTEGER REFERENCES solar_installation(installation_id) ON DELETE SET NULL,
  capacity_kwh NUMERIC(8,2) CHECK (capacity_kwh >= 0),
  current_charge_pct NUMERIC(5,2) CHECK (current_charge_pct BETWEEN 0 AND 100),
  status VARCHAR(20) CHECK (status IN ('charging','discharging','idle','fault')),
  last_updated TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE energy_consumption_log (
  log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_id INTEGER REFERENCES zone(zone_id) ON DELETE SET NULL,
  equipment_id INTEGER REFERENCES equipment(equipment_id) ON DELETE SET NULL,
  source_id INTEGER REFERENCES power_source(source_id) ON DELETE SET NULL,
  timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  kwh_consumed NUMERIC(8,3) NOT NULL CHECK (kwh_consumed >= 0),
  CONSTRAINT chk_consumption_granularity CHECK (zone_id IS NOT NULL OR equipment_id IS NOT NULL)
);
CREATE INDEX idx_consume_timestamp ON energy_consumption_log(timestamp DESC);
