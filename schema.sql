CREATE INDEX idx_detected_inspection ON detected_item(inspection_id);

-- 5. SECURITY & BOARDING LOGS
CREATE TABLE security_gate_log (
  gate_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
