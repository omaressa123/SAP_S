-- 9. DEVICES & EQUIPMENT
CREATE TABLE equipment (
  equipment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_type VARCHAR(30) NOT NULL CHECK (equipment_type IN (
    'smart_login_kiosk','checkin_kiosk','baggage_scanner','security_gate',
    'boarding_gate_display','camera','solar_panel_array','battery_bank')),
  label VARCHAR(100),
  serial_number VARCHAR(50) UNIQUE,
  model VARCHAR(50),
  zone_id INTEGER REFERENCES zone(zone_id) ON DELETE SET NULL,
  install_date DATE,
  firmware_version VARCHAR(20),
  status VARCHAR(20) CHECK (status IN ('operational','degraded','down','under_maintenance')),
  last_health_check TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_equipment_zone ON equipment(zone_id);
CREATE INDEX idx_equipment_type ON equipment(equipment_type);
DROP TRIGGER IF EXISTS trg_equipment_updated ON equipment;
CREATE TRIGGER trg_equipment_updated BEFORE UPDATE ON equipment
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE equipment_health_check (
  check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_id INTEGER NOT NULL REFERENCES equipment(equipment_id) ON DELETE CASCADE,
  check_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  metric_type VARCHAR(30) CHECK (metric_type IN ('cpu_temp','network_latency','uptime','camera_feed_status')),
  value NUMERIC(8,2),
  status_result VARCHAR(20) CHECK (status_result IN ('ok','warning','critical'))
);
CREATE INDEX idx_ehc_equipment_time ON equipment_health_check(equipment_id, check_time DESC);

-- 1. IDENTITY & FACE RECOGNITION
CREATE TABLE passenger (
  passenger_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  date_of_birth DATE,
  nationality_country_code CHAR(2) REFERENCES country(country_code) ON DELETE RESTRICT,
  phone VARCHAR(20),
  email VARCHAR(100) UNIQUE,
  biometric_consent BOOLEAN NOT NULL DEFAULT FALSE,
  consent_date TIMESTAMPTZ,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT chk_consent_date CHECK (biometric_consent = FALSE OR consent_date IS NOT NULL)
);
DROP TRIGGER IF EXISTS trg_passenger_updated ON passenger;
CREATE TRIGGER trg_passenger_updated BEFORE UPDATE ON passenger
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

